export function numberedDocument(doc: SourceDoc, lines: string[] = doc.lines): string {
  const width = String(lines.length).length;
  const body = lines.map((l, i) => `${String(i + 1).padStart(width, '0')}| ${l}`).join('\n');
  return `<document name="${doc.name.replace(/"/g, "'")}">\n${body}\n</document>`;
}

export function unitList(reqs: Requirement[]): string {
  return reqs
    .map((r) => {
      const lines = r.lineStart === r.lineEnd ? `стр. ${r.lineStart}` : `стр. ${r.lineStart}–${r.lineEnd}`;
      return `${r.id} [${r.kind}${r.docId ? `, в документе «${r.docId}»` : ''}, ${lines}]: ${r.summary}`;
    })
    .join('\n');
}
